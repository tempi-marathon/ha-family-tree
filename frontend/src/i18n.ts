export function pickLocale(language?: string): Record<LocaleKey, string> {
  const lang = (language || "en").toLowerCase();
  if (lang.startsWith("nl")) return NL;
  return { ...EN };
}

export function t(
  language: string | undefined,
  key: LocaleKey,
): string {
  return pickLocale(language)[key] ?? EN[key] ?? key;
}
